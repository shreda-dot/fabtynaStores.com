-- =====================================================================
-- Accounting cross-table constraints (loans, expenses)
-- =====================================================================
-- Prisma cannot express the mutual reference between `expenses` and
-- `loan_repayments` (each holds a nullable FK to the other), nor a CHECK
-- that reads another table. Both are installed here.

-- ---------------------------------------------------------------------
-- 1. Mutual links between a loan repayment and the interest expense it
--    generated. Both directions are DEFERRABLE so the pair can be inserted
--    inside a single transaction in either order.
-- ---------------------------------------------------------------------
ALTER TABLE loan_repayments
  ADD CONSTRAINT fk_loan_repayments_expense
  FOREIGN KEY ("expenseId") REFERENCES expenses (id)
  ON DELETE RESTRICT ON UPDATE CASCADE
  DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE expenses
  ADD CONSTRAINT fk_expenses_loan_repayment
  FOREIGN KEY ("loanRepaymentId") REFERENCES loan_repayments (id)
  ON DELETE RESTRICT ON UPDATE CASCADE
  DEFERRABLE INITIALLY DEFERRED;

-- ---------------------------------------------------------------------
-- 2. An expense generated by a loan repayment must be categorised as
--    LOAN_INTEREST. The reverse is not required: a manual LOAN_INTEREST
--    expense may exist without a repayment.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_check_expense_loan_link()
RETURNS trigger AS $$
BEGIN
  IF NEW."loanRepaymentId" IS NOT NULL AND NEW.category <> 'LOAN_INTEREST' THEN
    RAISE EXCEPTION 'An expense linked to a loan repayment (loanRepaymentId=%) must use category LOAN_INTEREST, got %.',
      NEW."loanRepaymentId", NEW.category;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_expenses_loan_link
  BEFORE INSERT OR UPDATE ON expenses
  FOR EACH ROW EXECUTE FUNCTION fn_check_expense_loan_link();

-- ---------------------------------------------------------------------
-- 3. Loan ledger source exclusivity: REPAYMENT entries must carry the
--    repayment id; DISBURSEMENT and CHARGE entries must not.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_check_loan_ledger_source()
RETURNS trigger AS $$
BEGIN
  IF NEW.type = 'REPAYMENT' AND NEW."loanRepaymentId" IS NULL THEN
    RAISE EXCEPTION 'A REPAYMENT loan ledger entry must reference its loanRepaymentId.';
  END IF;
  IF NEW.type <> 'REPAYMENT' AND NEW."loanRepaymentId" IS NOT NULL THEN
    RAISE EXCEPTION 'Only REPAYMENT loan ledger entries may reference a loanRepaymentId.';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_loan_ledger_source
  BEFORE INSERT ON loan_ledger_entries
  FOR EACH ROW EXECUTE FUNCTION fn_check_loan_ledger_source();
