-- =====================================================================
-- Admin user roles, activation and last sign-in
-- =====================================================================
-- Additive only: three new columns on `admin_users` plus the `AdminRole`
-- enum. No existing column is touched.
--
-- WHY THIS FILE IS NOT EXACTLY WHAT `prisma migrate dev` EMITTED
-- --------------------------------------------------------------
-- `prisma migrate dev --create-only` ALSO produced two
-- `ALTER TABLE ... DROP CONSTRAINT` statements for
-- `fk_expenses_loan_repayment` and `fk_loan_repayments_expense`. Those two
-- foreign keys are hand-written in `20261017000600_accounting_constraints`
-- because Prisma cannot express the mutual, DEFERRABLE reference between
-- `expenses` and `loan_repayments`; the schema therefore declares the columns
-- as plain scalars (`Expense.loanRepaymentId`, `LoanRepayment.expenseId`), so
-- Prisma's diff treats the FKs as "extra" objects and offers to delete them.
-- They were removed from this migration on purpose. Any future autogenerated
-- migration must be reviewed for the same two drops — `db:verify` now checks
-- both foreign keys by name so a silent loss is caught.
--
-- `role` IS NOT ENFORCED ANYWHERE YET: no code reads it and there is no
-- authorization layer, so every account still has full access. It defaults to
-- STAFF. Accounts are deactivated (`isActive = false`), never deleted —
-- purchases, sales, stock transfers and stock adjustments reference
-- `admin_users` with ON DELETE RESTRICT.

-- CreateEnum
CREATE TYPE "AdminRole" AS ENUM ('OWNER', 'STAFF');

-- AlterTable
ALTER TABLE "admin_users" ADD COLUMN     "isActive" BOOLEAN NOT NULL DEFAULT true,
ADD COLUMN     "lastLoginAt" TIMESTAMPTZ(3),
ADD COLUMN     "role" "AdminRole" NOT NULL DEFAULT 'STAFF';

-- ---------------------------------------------------------------------
-- Email is stored already normalised: lower-cased and trimmed. The seed
-- script normalises before writing too, but this CHECK is what makes the
-- guarantee hold no matter who writes the row.
-- ---------------------------------------------------------------------
ALTER TABLE admin_users
  ADD CONSTRAINT ck_admin_users_email_normalised
  CHECK (email = lower(btrim(email)));
