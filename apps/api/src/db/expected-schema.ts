/**
 * The exact database objects `db:verify` expects to find, by name.
 *
 * HOW THIS FILE IS MAINTAINED
 * ---------------------------
 * Every entry here is derived from the hand-written SQL in
 * `apps/api/prisma/migrations/**` — that SQL is the source of truth for the
 * database, so this list is a *mirror* of it, never an independent design.
 *
 * When a new migration adds a rule:
 *   1. Open the new `migration.sql`.
 *   2. Copy the object names it creates verbatim:
 *        - `ADD CONSTRAINT <name> CHECK (...)`  -> EXPECTED_CHECK_CONSTRAINTS
 *        - `CREATE TRIGGER <name>`              -> EXPECTED_TRIGGERS
 *        - `CREATE UNIQUE INDEX <name> ... WHERE ...` -> EXPECTED_PARTIAL_INDEXES
 *        - a hand-written `FOREIGN KEY`         -> EXPECTED_FOREIGN_KEYS
 *   3. Add the migration folder name to EXPECTED_MIGRATIONS.
 *   4. Run `pnpm --filter @fabtyna/api db:verify` against dev and test; it must
 *      report PASS for every new item.
 *
 * A migration that only changes data, or that drops an object, needs the list
 * updated the same way (remove the dropped name). If a name here is ever
 * missing from a database, `db:verify` fails loudly — that is the point.
 *
 * EXPECTED_FOREIGN_KEYS exists for a specific reason: Prisma cannot express the
 * mutual, DEFERRABLE reference between `expenses` and `loan_repayments`, so
 * those two FKs are hand-written (migration `20261017000600`) while the schema
 * declares the columns as plain scalars. `prisma migrate dev` therefore treats
 * them as "extra" and emits `DROP CONSTRAINT` for them in every autogenerated
 * migration. Checking them here turns that silent loss into a loud FAIL.
 * (Prisma-managed FKs are not listed: the schema declares them, so Prisma
 * regenerates them rather than dropping them.)
 *
 * `db:verify` also checks that each applied migration's file checksum still
 * matches the checksum Prisma recorded, which is what catches an *edited*
 * migration file. See `docs/backend-schema.md`.
 */

