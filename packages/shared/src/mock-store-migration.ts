/**
 * Non-destructive migration for the localStorage-backed mock store.
 *
 * Lives in `shared` (rather than inside the web app's mock-store) so it stays a
 * pure function over plain data and can be unit-tested. It never drops rows and
 * never resets a collection: unknown keys are preserved, missing collections
 * are created empty, and new fields are back-filled only when absent.
 */

export const MOCK_STORE_CURRENT_VERSION = 7;
export const ACCOUNT_MIGRATION_RECONCILIATION_NOTICE_ID =
  "mock-migration-v7-account-reconciliation";

type PersistedShape = Record<string, unknown>;

/**
 * Fixed, migration-owned ids for the two accounts every store starts with.
 * They are deliberately not generated by `newId()` (which is client-side in
 * the web app) so that a migrated payload is deterministic and repeatable.
 */
const DEFAULT_ACCOUNT_CASH_ID = "acct-cash-on-hand";
const DEFAULT_ACCOUNT_MONIEPOINT_ID = "acct-moniepoint";

const ACCOUNT_LEDGER_SOURCE_KEYS = [
  "salePaymentId",
  "customerPaymentId",
  "supplierPaymentId",
  "purchaseId",
  "expenseId",
  "otherIncomeId",
  "accountTransferId",
  "customerRefundId",
  "loanId",
  "loanRepaymentId",
] as const;

const ALL_COLLECTIONS = [
  "products",
  "suppliers",
  "customers",
  "purchases",
  "purchaseLines",
  "sales",
  "saleLines",
  "salePayments",
  "stockTransfers",
  "stockTransferLines",
  "stockTransferLegs",
  "stockAdjustments",
  "stockAdjustmentLines",
  "stockMovements",
  "supplierLedgerEntries",
  "supplierPayments",
  "customerLedgerEntries",
  "expenses",
  "loans",
  "loanLedgerEntries",
  "loanRepayments",
  "cashSnapshots",
  "auditLogs",
  "accounts",
  "accountLedgerEntries",
  "accountTransfers",
] as const;

function asArray(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

function asRecord(value: unknown): PersistedShape | null {
  if (value !== null && typeof value === "object" && !Array.isArray(value)) {
    return value as PersistedShape;
  }
  return null;
}

export interface MockStoreMigrationResult {
  version: number;
  data: PersistedShape;
}

/**
 * Migrates a decoded mock-store payload forward to
 * `MOCK_STORE_CURRENT_VERSION`. Returns `null` when the payload cannot be
 * migrated (not an object, or a version from the future) so the caller can fall
 * back to a reseed.
 */
export function migrateMockStoreData(
  version: number,
  data: unknown,
): MockStoreMigrationResult | null {
  if (!Number.isInteger(version) || version < 1) return null;
  if (version > MOCK_STORE_CURRENT_VERSION) return null;

  const root = asRecord(data);
  if (root === null) return null;

  const next: PersistedShape = { ...root };

  // Additive: guarantee every collection exists so older payloads do not blow
  // up readers that assume an array.
  for (const key of ALL_COLLECTIONS) {
    if (!Array.isArray(next[key])) {
      next[key] = [];
    }
  }

  // v4 -> v5: purchases gained `paidKobo` and `dueDate`. Legacy purchases had
  // no credit concept, so they default to fully paid (paidKobo = totalKobo).
  next.purchases = asArray(next.purchases).map((row) => {
    const purchase = asRecord(row);
    if (purchase === null) return row;
    const totalKobo = purchase.totalKobo;
    const hasPaid = typeof purchase.paidKobo === "string";
    return {
      ...purchase,
      paidKobo: hasPaid
        ? purchase.paidKobo
        : typeof totalKobo === "string"
          ? totalKobo
          : "0",
      dueDate: purchase.dueDate === undefined ? null : purchase.dueDate,
    };
  });

  // v4 -> v5: expenses gained `loanRepaymentId`.
  next.expenses = asArray(next.expenses).map((row) => {
    const expense = asRecord(row);
    if (expense === null) return row;
    return {
      ...expense,
      loanRepaymentId:
        expense.loanRepaymentId === undefined ? null : expense.loanRepaymentId,
    };
  });

  // v5 -> v6: the loan-repayment -> expense link became one-directional, so
  // `loanRepayments[].expenseId` no longer exists in the DTO. Saved payloads
  // still carry it; drop only that key so a round-trip through the now-strict
  // `loanRepaymentDtoSchema` keeps parsing. No rows are dropped and no other
  // key is touched.
  next.loanRepayments = asArray(next.loanRepayments).map((row) => {
    const repayment = asRecord(row);
    if (repayment === null || !("expenseId" in repayment)) return row;
    const rest = { ...repayment };
    delete rest.expenseId;
    return rest;
  });

  // v6 -> v7: accounts become the single source of truth for money. This step
  // is NOT idempotent (it synthesises ledger rows), so it is gated on the
  // incoming version: a payload that already carries the accounts feature is
  // never re-backfilled.
  if (version < 7) {
    backfillAccounts(next);
  }

  return { version: MOCK_STORE_CURRENT_VERSION, data: next };
}

/**
 * Synthesises the account ledger that the legacy money rows implied.
 *
 * - Every sale payment took money IN; every supplier payment paid money OUT.
 * - A supplier-less purchase that was paid is money OUT keyed on the purchase.
 * - Whenever the source document is VOIDED, the entry is posted together with
 *   its reversal so the pair nets to zero — a voided document never leaves
 *   only the money-in (or only the money-out) behind.
 * - Each account is stamped with the default it maps to (transfers ->
 *   Moniepoint, everything else -> cash on hand).
 * - If a chronological running balance would dip below zero, an OPENING_BALANCE
 *   dated before that account's earliest row lifts the low-water mark to zero.
 */
function backfillAccounts(next: PersistedShape): void {
  const salesById = new Map<string, PersistedShape>();
  for (const row of asArray(next.sales)) {
    const sale = asRecord(row);
    if (sale !== null && typeof sale.id === "string") salesById.set(sale.id, sale);
  }
  const purchasesById = new Map<string, PersistedShape>();
  for (const row of asArray(next.purchases)) {
    const purchase = asRecord(row);
    if (purchase !== null && typeof purchase.id === "string") {
      purchasesById.set(purchase.id, purchase);
    }
  }

  // Money that left via a transfer left through the bank account; everything
  // else (cash, other) left the drawer.
  const accountForMethod = (method: unknown): string =>
    method === "TRANSFER"
      ? DEFAULT_ACCOUNT_MONIEPOINT_ID
      : DEFAULT_ACCOUNT_CASH_ID;

  next.salePayments = asArray(next.salePayments).map((row) => {
    const payment = asRecord(row);
    if (payment === null) return row;
    return {
      ...payment,
      accountId:
        typeof payment.accountId === "string"
          ? payment.accountId
          : DEFAULT_ACCOUNT_CASH_ID,
    };
  });

  next.supplierPayments = asArray(next.supplierPayments).map((row) => {
    const payment = asRecord(row);
    if (payment === null) return row;
    return {
      ...payment,
      accountId:
        typeof payment.accountId === "string"
          ? payment.accountId
          : accountForMethod(payment.method),
    };
  });

  next.expenses = asArray(next.expenses).map((row) => {
    const expense = asRecord(row);
    if (expense === null) return row;
    return {
      ...expense,
      voidedAt: expense.voidedAt === undefined ? null : expense.voidedAt,
      voidReason: expense.voidReason === undefined ? null : expense.voidReason,
    };
  });

  let ledgerSeq = 0;
  const accountLedger: PersistedShape[] = [];

  const appendEntry = (seed: {
    accountId: string;
    type: string;
    amountKobo: string;
    occurredAt: string;
    source: Partial<Record<(typeof ACCOUNT_LEDGER_SOURCE_KEYS)[number], string>>;
    voided: boolean;
  }): void => {
    ledgerSeq += 1;
    const entry: PersistedShape = {
      id: `mig7-ale-${ledgerSeq}`,
      accountId: seed.accountId,
      type: seed.type,
      amountKobo: seed.amountKobo,
      note: null,
      occurredAt: seed.occurredAt,
      reversesEntryId: null,
      ...seed.source,
    };
    for (const key of ACCOUNT_LEDGER_SOURCE_KEYS) {
      if (!(key in entry)) entry[key] = null;
    }
    accountLedger.push(entry);

    if (!seed.voided) return;
    ledgerSeq += 1;
    accountLedger.push({
      ...entry,
      id: `mig7-ale-${ledgerSeq}`,
      amountKobo: seed.amountKobo.startsWith("-")
        ? seed.amountKobo.slice(1)
        : `-${seed.amountKobo}`,
      reversesEntryId: entry.id,
    });
  };

  for (const row of asArray(next.salePayments)) {
    const payment = asRecord(row);
    if (
      payment === null ||
      typeof payment.id !== "string" ||
      typeof payment.amountKobo !== "string" ||
      typeof payment.paidAt !== "string" ||
      typeof payment.accountId !== "string"
    ) {
      continue;
    }
    const sale =
      typeof payment.saleId === "string"
        ? salesById.get(payment.saleId)
        : undefined;
    appendEntry({
      accountId: payment.accountId,
      type: "SALE_PAYMENT",
      amountKobo: payment.amountKobo,
      occurredAt: payment.paidAt,
      source: { salePaymentId: payment.id },
      voided: sale !== undefined && sale.status === "VOIDED",
    });
  }

  for (const row of asArray(next.expenses)) {
    const expense = asRecord(row);
    if (
      expense === null ||
      typeof expense.id !== "string" ||
      typeof expense.amountKobo !== "string" ||
      typeof expense.expenseDate !== "string" ||
      expense.category === "LOAN_INTEREST" ||
      expense.amountKobo === "0" ||
      expense.amountKobo.startsWith("-")
    ) {
      continue;
    }
    appendEntry({
      accountId: DEFAULT_ACCOUNT_CASH_ID,
      type: "EXPENSE",
      amountKobo: `-${expense.amountKobo}`,
      occurredAt: expense.expenseDate,
      source: { expenseId: expense.id },
      voided: expense.voidedAt !== null && expense.voidedAt !== undefined,
    });
  }

  for (const row of asArray(next.loans)) {
    const loan = asRecord(row);
    if (
      loan === null ||
      typeof loan.id !== "string" ||
      typeof loan.principalKobo !== "string" ||
      typeof loan.disbursedAt !== "string" ||
      loan.principalKobo === "0" ||
      loan.principalKobo.startsWith("-")
    ) {
      continue;
    }
    appendEntry({
      accountId: DEFAULT_ACCOUNT_CASH_ID,
      type: "LOAN_DISBURSEMENT",
      amountKobo: loan.principalKobo,
      occurredAt: loan.disbursedAt,
      source: { loanId: loan.id },
      voided: false,
    });
  }

  for (const row of asArray(next.loanRepayments)) {
    const repayment = asRecord(row);
    if (
      repayment === null ||
      typeof repayment.id !== "string" ||
      typeof repayment.amountKobo !== "string" ||
      typeof repayment.paidAt !== "string" ||
      repayment.amountKobo === "0" ||
      repayment.amountKobo.startsWith("-")
    ) {
      continue;
    }
    appendEntry({
      accountId: DEFAULT_ACCOUNT_CASH_ID,
      type: "LOAN_REPAYMENT",
      amountKobo: `-${repayment.amountKobo}`,
      occurredAt: repayment.paidAt,
      source: { loanRepaymentId: repayment.id },
      voided: false,
    });
  }

  for (const row of asArray(next.supplierPayments)) {
    const payment = asRecord(row);
    if (
      payment === null ||
      typeof payment.id !== "string" ||
      typeof payment.amountKobo !== "string" ||
      typeof payment.paidAt !== "string" ||
      typeof payment.accountId !== "string"
    ) {
      continue;
    }
    const purchase =
      typeof payment.purchaseId === "string"
        ? purchasesById.get(payment.purchaseId)
        : undefined;
    appendEntry({
      accountId: payment.accountId,
      type: "SUPPLIER_PAYMENT",
      amountKobo: `-${payment.amountKobo}`,
      occurredAt: payment.paidAt,
      source: { supplierPaymentId: payment.id },
      voided: purchase !== undefined && purchase.status === "VOIDED",
    });
  }

  // A supplier-less cash purchase has no payment row to hang the outflow on,
  // so its paid amount is recorded against the purchase itself.
  for (const row of asArray(next.purchases)) {
    const purchase = asRecord(row);
    if (purchase === null || typeof purchase.id !== "string") continue;
    if (purchase.supplierId !== null) continue;
    const paidKobo = typeof purchase.paidKobo === "string" ? purchase.paidKobo : "0";
    if (paidKobo === "0" || paidKobo.startsWith("-")) continue;
    appendEntry({
      accountId: DEFAULT_ACCOUNT_CASH_ID,
      type: "PURCHASE_PAYMENT",
      amountKobo: `-${paidKobo}`,
      occurredAt:
        typeof purchase.purchasedAt === "string"
          ? purchase.purchasedAt
          : new Date(0).toISOString(),
      source: { purchaseId: purchase.id },
      voided: purchase.status === "VOIDED",
    });
  }

  // The opening balance is only added when the live running balance would dip
  // below zero. Entries sharing an instant are netted first — a voided
  // document's entry AND its mirror reversal sit at the same instant and must
  // net to zero, exactly as they do in the account balance. It also avoids a
  // spurious dip when an outflow and an inflow fall on the same timestamp.
  const chronological = [...accountLedger].sort((a, b) =>
    String(a.occurredAt).localeCompare(String(b.occurredAt)),
  );

  const runningByAccount = new Map<string, { running: bigint; min: bigint }>();
  const earliestByAccount = new Map<string, string>();
  let cursor = 0;
  while (cursor < chronological.length) {
    const occurredAt = String(chronological[cursor].occurredAt);
    const netByAccount = new Map<string, bigint>();
    while (
      cursor < chronological.length &&
      String(chronological[cursor].occurredAt) === occurredAt
    ) {
      const entry = chronological[cursor];
      const accountId = String(entry.accountId);
      netByAccount.set(
        accountId,
        (netByAccount.get(accountId) ?? 0n) + BigInt(String(entry.amountKobo)),
      );
      cursor += 1;
    }
    for (const [accountId, delta] of netByAccount) {
      const state = runningByAccount.get(accountId) ?? { running: 0n, min: 0n };
      state.running += delta;
      if (state.running < state.min) state.min = state.running;
      runningByAccount.set(accountId, state);
      if (!earliestByAccount.has(accountId)) {
        earliestByAccount.set(accountId, occurredAt);
      }
    }
  }

  for (const [accountId, state] of runningByAccount) {
    if (state.min >= 0n) continue;
    const earliest = earliestByAccount.get(accountId) ?? new Date(0).toISOString();
    ledgerSeq += 1;
    const opening: PersistedShape = {
      id: `mig7-ale-${ledgerSeq}`,
      accountId,
      type: "OPENING_BALANCE",
      amountKobo: (-state.min).toString(),
      note: "Opening balance carried from records before accounts existed",
      occurredAt: new Date(new Date(earliest).getTime() - 86_400_000).toISOString(),
      reversesEntryId: null,
    };
    for (const key of ACCOUNT_LEDGER_SOURCE_KEYS) opening[key] = null;
    accountLedger.push(opening);
  }

  next.accountLedgerEntries = accountLedger;

  const auditLogs = asArray(next.auditLogs);
  if (
    !auditLogs.some(
      (row) => asRecord(row)?.id === ACCOUNT_MIGRATION_RECONCILIATION_NOTICE_ID,
    )
  ) {
    next.auditLogs = [
      ...auditLogs,
      {
        id: ACCOUNT_MIGRATION_RECONCILIATION_NOTICE_ID,
        actorId: null,
        action: "ACCOUNT_MIGRATION_RECONCILIATION_REQUIRED",
        entityType: "MockStoreMigration",
        entityId: ACCOUNT_MIGRATION_RECONCILIATION_NOTICE_ID,
        beforeData: null,
        afterData: {
          accountIds: [DEFAULT_ACCOUNT_CASH_ID, DEFAULT_ACCOUNT_MONIEPOINT_ID],
        },
        metadata: null,
        occurredAt: chronological[0]?.occurredAt ?? new Date(0).toISOString(),
      },
    ];
  }

  // The two default accounts always exist after the migration. If a payload
  // somehow already carries accounts, they are left untouched.
  if (asArray(next.accounts).length === 0) {
    const createdAt =
      chronological.length > 0
        ? String(chronological[0].occurredAt)
        : new Date(0).toISOString();
    next.accounts = [
      {
        id: DEFAULT_ACCOUNT_CASH_ID,
        name: "Cash on hand",
        type: "CASH",
        isActive: true,
        deactivatedAt: null,
        note: "Money physically in the drawer.",
        createdAt,
        updatedAt: createdAt,
      },
      {
        id: DEFAULT_ACCOUNT_MONIEPOINT_ID,
        name: "Moniepoint",
        type: "BANK",
        isActive: true,
        deactivatedAt: null,
        note: "Bank / transfer account.",
        createdAt,
        updatedAt: createdAt,
      },
    ];
  }

  if (!Array.isArray(next.accountTransfers)) next.accountTransfers = [];
}
